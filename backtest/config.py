"""模組三（回測）設定。

回測的目的是回答一個很具體的問題：**模組一的計分策略，若在過去十五年
真的照著做，績效會是什麼樣子？** 因此這裡的原則是「盡量沿用模組一的
既有定義」——計分函式、類別權重、部位階梯全部 import 自 liquidity_monitor，
不另寫一份。任何為了回測而不得不做的偏離，都在這個檔案裡集中列出並說明。
"""
from __future__ import annotations

# ---------------------------------------------------------------------------
# 期間與標的
# ---------------------------------------------------------------------------
BACKTEST_YEARS = 15

QQQ, TQQQ, SGOV = "QQQ", "TQQQ", "SGOV"

# SGOV 2020-05-26 才成立，涵蓋不到十五年。BIL（SPDR 1-3 個月美國國庫券 ETF，
# 2007-05 成立）是同一類工具、同一個角色，用來銜接 2020 年之前的現金部位。
#
# 這是回測必要的替代，不是無傷大雅的細節，因此：
#   1. 有 SGOV 就用 SGOV，只有更早的期間才用 BIL
#   2. 兩者重疊期間的報酬差異會被實際量出來寫進報告（見 data.splice_cash）
#      ——不量就等於宣稱「它們一樣」，而那是沒有根據的
CASH_PROXY = "BIL"

PRICE_TICKERS = (QQQ, TQQQ, SGOV, CASH_PROXY)

# 銜接品質門檻：重疊期間的年化報酬差異超過這個值就不當成可互換，
# 直接讓回測失敗而不是默默接受。0.5%/年對現金部位而言已經很大。
MAX_CASH_SPLICE_ANNUAL_DIFF_PCT = 0.5

# ---------------------------------------------------------------------------
# 依使用者要求：回測不納入 ⑥ 政策方向
# ---------------------------------------------------------------------------
# ⑥ 的三項在回測情境下各有問題：FOMC 決議偏向需要逐次會議的 AI 判讀、
# CME FedWatch 沒有歷史頁面可讀。使用者明確要求排除整個 ⑥。
#
# composite_score 對缺少的類別會**按比例重新分配權重**，因此排除 ⑥ 之後
# 其餘五類的相對權重會從 (10,20,10,15,15)/70 放大——這不是 bug，是既有
# 設計，但它代表回測的綜合分數與線上分數不是同一個東西，報告必須講明。
EXCLUDED_CATEGORIES = ("policy_direction",)

# 沒有歷史序列、回測期間無法重建的指標。
#   ndx_breadth_200d  需要「當時的成分股名單」才能正確回推，
#                     用今天的名單回推會有嚴重的存活者偏誤
#   etf_fund_flow     由本專案每日自行觀測累積而來，沒有回溯資料
#
# 這兩項被排除後，③ 只剩 move_index 一項、⑤ 只剩兩項。類別平均本來就
# 只對「有值的項目」取平均，所以不會出錯，但同樣要在報告裡講明。
UNAVAILABLE_ITEMS = ("ndx_breadth_200d", "etf_fund_flow")

# ---------------------------------------------------------------------------
# 部位階梯 -> 實際權重
# ---------------------------------------------------------------------------
# 刻意寫成明確對照表，而不是去解析 POSITION_LADDER 裡的中文字串。
# 解析字串的話，階梯文案日後改一個字，回測會安靜地配出錯誤的權重；
# 有對照表就能在測試裡強制「每一個階梯都必須有對應」，改了就會失敗。
LADDER_WEIGHTS = {
    "50% TQQQ + 50% QQQ": {TQQQ: 0.50, QQQ: 0.50},
    "25% TQQQ + 75% QQQ": {TQQQ: 0.25, QQQ: 0.75},
    "100% QQQ": {QQQ: 1.00},
    "100% SGOV": {SGOV: 1.00},
}

# 閘門上限對應的權重覆寫
CAP_WEIGHTS = {
    "SGOV": {SGOV: 1.00},      # Gate A 強制清倉
    "QQQ": {QQQ: 1.00},        # 禁用槓桿
}

# ---------------------------------------------------------------------------
# 交易假設
# ---------------------------------------------------------------------------
# 訊號用當日收盤資料算出，最快只能在**下一個交易日**才成交。
# 用當日收盤價成交等於拿當天的收盤資訊去買當天的收盤價，是前視偏誤。
EXECUTION_LAG_DAYS = 1

# 單邊換手成本（基點）。TQQQ 與 QQQ 的價差都很小，但策略會在階梯之間
# 來回切換，成本累積起來並非可以忽略。設成參數是為了讓報告能同時呈現
# 「零成本」與「含成本」兩種結果——若兩者差距大到會改變結論，那個結論
# 本來就不該當成結論。
COST_BPS_PER_SIDE = 5.0

# 只在階梯分級改變時才換倉。策略本身是離散的（五個分級），
# 每日照著權重微調會產生大量無意義的換手。
REBALANCE_ON_CHANGE_ONLY = True

TRADING_DAYS_PER_YEAR = 252

DATA_ROOT = "docs/data/backtest"
CACHE_ROOT = "data/backtest"
