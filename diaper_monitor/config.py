"""模組八（尿布單價監控）設定。

**量測對象**：尿布 M 號，三個品牌／通路各自視為獨立的監控對象——
「滿意寶寶日本境內版」「Aiwibi」「奢寵幫」彼此不是同一件商品的不同賣場，
價格本來就不該放在一起比大小，只在各自的時間序列上比「今天 vs. 自己的近期」。

**資料來源以人工填入為主，自動爬蟲為輔。** 蝦皮、momo、PChome 等平台對非登入的
自動化請求有防爬機制，貿然爬取容易撞到服務條款、也容易因頁面改版而悄悄爬錯
（爬蟲最危險的失敗方式不是報錯，是安靜地回傳一個過期或錯誤的數字）。
比照模組一 `manual_overrides.json` 的前例：人工查價填進
`data/diaper_monitor/manual_prices.csv` 一律信任；`sources/` 底下的自動爬蟲
（目前只有 PChome，理由見 `sources/pchome.py`）輸出到獨立的
`data/diaper_monitor/scraped_prices.csv`，**兩邊同一天、同一品牌、同一平台
都有資料時，以人工填的為準**——爬蟲的角色是補人工沒空查、或忘記查的空檔，
不是取代查證。新增其他平台的爬蟲時，一樣輸出跟這份 CSV 相同的欄位
（date, brand, platform, product_name, pack_price, piece_count, url），
不需要動 `pipeline.py` 的合併邏輯。

**「今日最便宜」怎麼算**：同一天、同一品牌可能有好幾個平台的報價，
取單片價（= 包裝售價 / 片數）最低的那一筆，作為當日代表值。
用最低價而非平均價，是因為使用者實際能拿到的價格就是各平台裡最便宜的那個，
用平均會把「其實有更便宜的選擇」這件事平均掉。
"""
from __future__ import annotations

SIZE = "M"

# 監控品牌／通路。順序即為儀表板呈現順序。
BRANDS = ["滿意寶寶日本境內版", "Aiwibi", "奢寵幫"]

# 每天查價至少要涵蓋的平台。`platform` 欄位本身是自由文字（不做驗證），
# 這份清單只是給填表的人一個底線——這三個查了，其餘平台（藥妝通路、品牌官網等）
# 有查到當然可以一起填，但不能只填這些之外的平台卻漏掉這三個。
PLATFORMS = ["蝦皮", "酷澎", "momo購物網"]

MANUAL_PRICES_PATH = "data/diaper_monitor/manual_prices.csv"
SCRAPED_PRICES_PATH = "data/diaper_monitor/scraped_prices.csv"
HISTORY_PATH = "data/diaper_monitor/history.csv"
DATA_ROOT = "docs/data/diaper"

# 自動爬蟲抓到的商品標題必須同時通過這兩關才會被採用：確實是 M 號、
# 且標題上找得到片數。抓不到片數就沒辦法換算單片價；沒標 M 號的話很可能是
# 別的尺寸，兩者都寧可漏抓，不要抓錯——抓錯的資料會直接誤導「顯著下跌」的判定。
PIECE_COUNT_PATTERN = r"(\d+)\s*片"
SIZE_M_PATTERN = r"(?<![A-Za-z])M(?![A-Za-z])"

# 上面兩關防不了的三種標題，全是 2026-08-18 第一次在 GitHub Actions 上真的
# 跑起來時抓到的真實案例（見 PR #78 之後那次修正的說明），不是憑空想像：
#
#   體驗包／試用包       「零觸感瞬吸...2片/包 M-2XL(體驗包)」→ 2片賣29元，
#                        算出 14.5 元/片——試用包單價本來就貴，不是市售單位
#   多尺寸片數擠在一起   「夜用甄柔瞬吸...(單包入48/44/40/36片)」→ 規則抓到
#                        「36」，但哪個數字對應 M 號其實不確定
#   箱購倍數             「奢寵幫 M 38片入*3包入(箱購)」→ 規則只抓到「38」，
#                        沒乘以 3，算出 40 元/片，實際應該接近 13 元/片
#
# 前兩種寧可整批跳過，不要猜——猜對了也只是運氣好。
#
# **第三種（箱購）已經改由 PACK_MULTIPLIER_PATTERN 換算，不再整批跳過。**
# 理由是它跟前兩種不一樣：38 片、3 包兩個數字都明明白白寫在標題上，乘起來
# 是算得出來的，不是猜。而且 2026-08-25 的實測顯示，這條規則正在造成
# 更嚴重的後果——奢寵幫在 PChome 查到的 4 筆全被擋掉，其中只有這一筆
# 同時標明了 M 號與片數，擋掉它等於這個品牌完全沒有自動報價。
# 換算錯了的話，由 PLAUSIBLE_UNIT_PRICE_RANGE 在最終單片價那一關再擋一次。
UNRELIABLE_TITLE_PATTERN = r"體驗包|試用|分享包|旅行包|\d+\s*/\s*\d+\s*/\s*\d+"

# 換算出來的單包售價如果落在這個範圍外，整批跳過——用來擋「換算係數猜錯」
# 這種價格會暴衝或趨近於零、但標題篩選全部過關的錯誤。蝦皮的搜尋 API 價格
# 欄位常見以「元的十萬分之一」為單位（實際換算係數未經驗證，見
# `sources/shopee.py` 開頭說明），這個範圍就是專門防那個換算沒做對時，
# 錯得離譜但形式上仍是個「數字」的結果被當成真報價收下。
# 10～10000 元是尿布單包售價的寬鬆常識範圍，不是回測校準值。
PLAUSIBLE_PACK_PRICE_RANGE = (10.0, 10000.0)

# 「近期平均」的比較視窗（天數，非交易日）。
# 太短（例如 3 天）容易被單一天的異常報價牽著走；太長則會把一個月前的價格
# 也當成「近期」，跌價後很久都還顯示「顯著下跌」。14 天是折衷值，非回測校準。
BASELINE_WINDOW_DAYS = 14

# 視窗內至少要有幾個歷史資料點，才採信「近期平均」這個基準。
# 剛上線或某幾天忘記填資料時，1、2 筆資料算出的「平均」雜訊極大，
# 用來判定「跌 20%」會做出沒有根據的標示——寧可先顯示「資料不足」。
MIN_BASELINE_POINTS = 5

# 顯著下跌門檻：今日最便宜單價 vs. 近期平均，跌幅達此比例即標示。
DROP_THRESHOLD_PCT = 20.0

# 資料斷料多少天算異常。**這一條是實測出來的。**
#
# 2026-08-15 之後人工沒再填、三個自動爬蟲每天都回 0 筆，於是儀表板連續十天
# 顯示同一組 08-15 的價格。而 GitHub Actions 每天照樣綠燈、照樣 commit ——
# 因為每天真的有東西變：latest.json 的 as_of 從昨天改成今天，其餘一字未動。
# 十天下來沒有任何一個地方叫過。
#
# 門檻放 3 天而不是 1 天：人工查價本來就可能週末跳過一兩天，天天紅燈會讓
# 這個訊號很快被無視。但 3 天以上就不是「今天忘了」，是斷料。
STALE_ALERT_DAYS = 3

# 箱購（同一個標題裡「N 片」又「M 包入」）要不要換算成總片數。
#
# 原本一律整批跳過，理由是「奢寵幫 M 38片入*3包入(箱購)」只抓到 38、
# 沒乘以 3，會算出 40 元/片而不是接近 13。但那個標題其實把兩個數字都寫清楚了
# ——38 片、3 包——乘起來是算得出來的，不是用猜的。
#
# 仍然只在**倍數明確寫在標題上**時才換算；「多尺寸片數擠在一起」
# （單包入48/44/40/36片）那種哪個數字對應 M 號不確定的，照樣跳過。
PACK_MULTIPLIER_PATTERN = r"[×xX*]\s*(\d+)\s*包"

# 換算出來的**單片價**合理範圍（元/片）。
#
# 既有的 PLAUSIBLE_PACK_PRICE_RANGE 檢查的是「一包多少錢」，擋不掉片數算錯——
# 一包 509 元是合理的，但片數若少算三倍，單片價會從 13 變成 40，而 509 這個
# 數字本身完全正常。真正會誤導「顯著下跌」判定的是單片價，所以要在那個數字上設防。
#
# 這一關同時擋住箱購換算的兩種錯法：忘了乘（偏高）與乘過頭（偏低）。
# 3～30 元是 M 號尿布的寬鬆常識範圍，不是回測校準值；目前人工填的三筆
# （6.42／8.21／11.55）都落在中間，而 config 註解記載的那個實際抓錯案例
# 「算出 40 元/片、應該接近 13」會被這一關擋下。
PLAUSIBLE_UNIT_PRICE_RANGE = (3.0, 30.0)
